export const dictionaries: Record<Lang, Partial<Record<StringKey, string>>> = { en, hi };

export function translate(lang: Lang, key: StringKey | string, params?: Record<string, string | number>): string {
  const dict = dictionaries[lang] as Record<string, string | undefined>;
  const fallback = dictionaries.en as Record<string, string | undefined>;
  const template = dict[key] ?? fallback[key] ?? key;
  return params ? template.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`)) : template;
}
